"""Generates Source/ui/TooltipText.cpp from the approved mockup (docs/mockups/.../mockup.html).

Usage: python tools/gen_tooltips.py [path to mockup.html]
The tables KMOD, KTIPS, UITIPS and TBA of the mockup hold the approved Russian texts (ASD-STE100).
"""
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent.parent
default = root / 'docs/mockups/m1-main-window-v15-2026-11-27/mockup.html'
mockup = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else default
src = mockup.read_text(encoding='utf-8')


def block(name):
    a = src.index('const %s = {' % name)
    b = src.index('\n};', a)
    return src[a:b]


def parse_entries(text):
    out = []
    for m in re.finditer(r"^\s*'?([\w.]+)'?\s*:\s*\[(.*)\],?\s*$", text, re.M):
        items = re.findall(r"'((?:[^'\\]|\\.)*)'|(TIPH|TIPW)", m.group(2))
        vals = []
        for s, t in items:
            vals.append('Совет' if t == 'TIPH' else 'Внимание' if t == 'TIPW' else s)
        out.append((m.group(1), vals))
    return out


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


kmod = parse_entries(block('KMOD'))
ktips = parse_entries(block('KTIPS'))
uitips = parse_entries(block('UITIPS'))

# threshold ring sections (tipHtml of the mockup)
ring = re.findall(r"sec\('Индикатор', '([^']*)'\)", src)
assert len(ring) == 2, ring
uitips.append(('thr.ring.inv', ['', '', ring[0], '', '', '']))
uitips.append(('thr.ring', ['', '', ring[1], '', '', '']))

# tonal balance advice (v7)
a = src.index('const TBA = [')
b = src.index('\n];', a)
tba = src[a:b]
bands = []
for m in re.finditer(r"\{ up: \['([^']*)',\s*\[(.*?)\]\],\s*dn: \['([^']*)',\s*\[(.*?)\]\] \}", tba, re.S):
    up_steps = re.findall(r"'([^']*)'", m.group(2))
    dn_steps = re.findall(r"'([^']*)'", m.group(4))
    bands.append((m.group(1), up_steps, m.group(3), dn_steps))
assert len(bands) == 6, len(bands)
# Low-mid below target: the first step of the mockup names the EQ band that cuts the range. The
# plugin builds that step at run time from the current EQ (D-028); the static list keeps a fallback.
lm = bands[2]
assert lm[3][0].startswith('Dynamic EQ уменьшает'), lm[3][0]
bands[2] = (lm[0], lm[1], lm[2], ['Dynamic EQ: Bell 250 Hz, Q 1.0, +1 dB.'] + lm[3][1:])

# multiband advice per band (v12)
a = src.index('const MBREC = {')
b = src.index('\n};', a)
mbrec = []
for m in re.finditer(r"^\s*(\w+):\s*\[(.*)\],?\s*$", src[a:b], re.M):
    texts = re.findall(r"'([^']*)'", m.group(2))
    assert len(texts) == 5, (m.group(1), len(texts))
    mbrec.append((m.group(1), texts))
assert len(mbrec) == 9, len(mbrec)

lines = ['// Generated by tools/gen_tooltips.py from %s (approved texts).' % mockup.relative_to(root).as_posix(),
         '// Regenerate instead of editing by hand.',
         '#include "ui/TooltipText.h"', '', 'namespace mm::ui::tips', '{',
         'const std::vector<ModuleText>& modules()', '{', '    static const std::vector<ModuleText> v {']
for k, v in kmod:
    lines.append('        { "%s", %s, %s },' % (k, cstr(v[0]), cstr(v[1])))
lines += ['    };', '    return v;', '}', '', 'const std::vector<KnobText>& knobs()', '{',
          '    static const std::vector<KnobText> v {']
for k, v in ktips:
    lines.append('        { "%s", %s, %s, %s, %s, %s },' % (k, cstr(v[0]), cstr(v[1]), cstr(v[2]), cstr(v[3]), cstr(v[4])))
lines += ['    };', '    return v;', '}', '', 'const std::vector<ControlText>& controls()', '{',
          '    static const std::vector<ControlText> v {']
for k, v in uitips:
    v = list(v)
    while len(v) < 6:
        v.append('')
    lines.append('        { "%s", %s, %s, %s, %s, %s, %s },' % (k, cstr(v[0]), cstr(v[1]), cstr(v[2]), cstr(v[3]), cstr(v[4]), cstr(v[5])))
lines += ['    };', '    return v;', '}', '', 'const std::vector<TonalAdvice>& tonalAdvice()', '{',
          '    static const std::vector<TonalAdvice> v {']
for up_heard, up_steps, dn_heard, dn_steps in bands:
    lines.append('        { %s, { %s }, %s, { %s } },' % (cstr(up_heard), ', '.join(cstr(x) for x in up_steps),
                                                         cstr(dn_heard), ', '.join(cstr(x) for x in dn_steps)))
lines += ['    };', '    return v;', '}', '', 'const std::vector<BandAdvice>& multibandAdvice()', '{',
          '    static const std::vector<BandAdvice> v {']
for k, texts in mbrec:
    lines.append('        { "mb.%s", { %s } },' % (k, ', '.join(cstr(t) for t in texts)))
lines += ['    };', '    return v;', '}', '} // namespace mm::ui::tips', '']
(root / 'Source/ui/TooltipText.cpp').write_text('\n'.join(lines), encoding='utf-8')
print(len(kmod), len(ktips), len(uitips), len(bands), len(mbrec))
